-- ============================================================
-- 4. CAPTURE FUNCTION
--
-- Receives the listings processed by one sync batch.
--
-- Inserts:
--   - parent listing state;
--   - each current variation state.
--
-- A row is inserted ONLY when the meaningful business state
-- differs from the most recent snapshot.
-- ============================================================

create or replace function
public.capture_ml_offer_state_snapshots(
  target_listing_ids uuid[],
  target_sync_run_id uuid
)
returns integer

language plpgsql

security invoker

set search_path = ''

as $$

declare

  inserted_listings integer :=
    0;

  inserted_variations integer :=
    0;

begin

  if (
    target_listing_ids
      is null
    or
    cardinality(
      target_listing_ids
    ) = 0
  ) then

    return 0;

  end if;


  -- ==========================================================
  -- PARENT LISTINGS
  -- ==========================================================

  insert into
  public.ml_offer_state_snapshots (

    organization_id,

    ml_account_id,

    ml_listing_id,

    ml_listing_variation_id,

    product_id,

    offer_scope,

    item_id,

    variation_id,

    seller_sku,

    title,

    listing_type_id,

    status,

    sub_status,

    price,

    available_quantity,

    sold_quantity,

    health,

    catalog_listing,

    is_current,

    ml_last_updated,

    captured_at,

    source_sync_run_id,

    source

  )

  select

    listing.organization_id,

    listing.ml_account_id,

    listing.id,

    null,

    listing.product_id,

    'listing',

    listing.item_id,

    null,

    listing.seller_sku,

    listing.title,

    listing.listing_type_id,

    listing.status,

    listing.sub_status,

    listing.price,

    listing.available_quantity,

    listing.sold_quantity,

    listing.health,

    listing.catalog_listing,

    listing.is_current,

    listing.ml_last_updated,

    now(),

    target_sync_run_id,

    'listings_sync'

  from
    public.ml_listings
      as listing

  left join lateral (

    select
      snapshot.*

    from
      public.ml_offer_state_snapshots
        as snapshot

    where
      snapshot.ml_listing_id =
        listing.id

      and
      snapshot.offer_scope =
        'listing'

    order by
      snapshot.captured_at desc,
      snapshot.id desc

    limit 1

  ) as previous
    on true

  where
    listing.id =
      any(
        target_listing_ids
      )

    and (

      previous.id
        is null

      or

      row(

        previous.product_id,

        previous.seller_sku,

        previous.title,

        previous.listing_type_id,

        previous.status,

        previous.sub_status,

        previous.price,

        previous.available_quantity,

        previous.sold_quantity,

        previous.health,

        previous.catalog_listing,

        previous.is_current

      )

      is distinct from

      row(

        listing.product_id,

        listing.seller_sku,

        listing.title,

        listing.listing_type_id,

        listing.status,

        listing.sub_status,

        listing.price,

        listing.available_quantity,

        listing.sold_quantity,

        listing.health,

        listing.catalog_listing,

        listing.is_current

      )

    );


  get diagnostics
    inserted_listings =
      row_count;


  -- ==========================================================
  -- VARIATIONS
  --
  -- Variation-specific price/stock/SKU are preferred.
  -- Parent listing provides title/status/health/catalog.
  -- ==========================================================

  insert into
  public.ml_offer_state_snapshots (

    organization_id,

    ml_account_id,

    ml_listing_id,

    ml_listing_variation_id,

    product_id,

    offer_scope,

    item_id,

    variation_id,

    seller_sku,

    title,

    listing_type_id,

    status,

    sub_status,

    price,

    available_quantity,

    sold_quantity,

    health,

    catalog_listing,

    is_current,

    ml_last_updated,

    captured_at,

    source_sync_run_id,

    source

  )

  select

    listing.organization_id,

    listing.ml_account_id,

    listing.id,

    variation.id,

    coalesce(
      variation.product_id,
      listing.product_id
    ),

    'variation',

    listing.item_id,

    variation.variation_id,

    coalesce(
      variation.seller_sku,
      listing.seller_sku
    ),

    listing.title,

    listing.listing_type_id,

    listing.status,

    listing.sub_status,

    coalesce(
      variation.price,
      listing.price
    ),

    coalesce(
      variation.available_quantity,
      listing.available_quantity
    ),

    coalesce(
      variation.sold_quantity,
      listing.sold_quantity
    ),

    listing.health,

    listing.catalog_listing,

    (
      listing.is_current
      and
      variation.is_current
    ),

    listing.ml_last_updated,

    now(),

    target_sync_run_id,

    'listings_sync'

  from
    public.ml_listing_variations
      as variation

  join
    public.ml_listings
      as listing

    on
      listing.id =
        variation.ml_listing_id

  left join lateral (

    select
      snapshot.*

    from
      public.ml_offer_state_snapshots
        as snapshot

    where
      snapshot.ml_listing_variation_id =
        variation.id

      and
      snapshot.offer_scope =
        'variation'

    order by
      snapshot.captured_at desc,
      snapshot.id desc

    limit 1

  ) as previous
    on true

  where
    variation.ml_listing_id =
      any(
        target_listing_ids
      )

    and (

      previous.id
        is null

      or

      row(

        previous.product_id,

        previous.seller_sku,

        previous.title,

        previous.listing_type_id,

        previous.status,

        previous.sub_status,

        previous.price,

        previous.available_quantity,

        previous.sold_quantity,

        previous.health,

        previous.catalog_listing,

        previous.is_current

      )

      is distinct from

      row(

        coalesce(
          variation.product_id,
          listing.product_id
        ),

        coalesce(
          variation.seller_sku,
          listing.seller_sku
        ),

        listing.title,

        listing.listing_type_id,

        listing.status,

        listing.sub_status,

        coalesce(
          variation.price,
          listing.price
        ),

        coalesce(
          variation.available_quantity,
          listing.available_quantity
        ),

        coalesce(
          variation.sold_quantity,
          listing.sold_quantity
        ),

        listing.health,

        listing.catalog_listing,

        (
          listing.is_current
          and
          variation.is_current
        )

      )

    );


  get diagnostics
    inserted_variations =
      row_count;


  return
    inserted_listings
    +
    inserted_variations;

end;

$$;


