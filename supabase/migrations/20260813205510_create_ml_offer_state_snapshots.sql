-- ============================================================
-- Speed Bikers Gestão V2
--
-- Historical state snapshots for Mercado Livre offers.
--
-- One offer can represent:
--   1. a listing itself;
--   2. a specific variation of a listing.
--
-- We store only meaningful state changes.
-- ============================================================


-- ============================================================
-- 1. TABLE
-- ============================================================

create table public.ml_offer_state_snapshots (

  id uuid primary key
    default gen_random_uuid(),

  organization_id uuid not null,

  ml_account_id uuid not null,

  ml_listing_id uuid not null,

  ml_listing_variation_id uuid,

  product_id uuid,

  offer_scope text not null
    check (
      offer_scope in (
        'listing',
        'variation'
      )
    ),

  item_id text not null,

  variation_id text,

  seller_sku text,

  title text,

  listing_type_id text,

  status text,

  sub_status jsonb not null
    default '[]'::jsonb,

  price numeric(18, 2),

  available_quantity integer,

  sold_quantity integer,

  health numeric(8, 4),

  catalog_listing boolean,

  is_current boolean not null
    default true,

  /*
   * Timestamp reported by Mercado Livre
   * for the parent listing.
   *
   * We keep it as evidence, but it will NOT
   * by itself create a new snapshot.
   */
  ml_last_updated timestamptz,

  /*
   * When V2 observed this state.
   */
  captured_at timestamptz not null
    default now(),

  /*
   * Synchronization that produced this observation.
   *
   * Nullable because in the future snapshots may also
   * be generated by webhooks or other collectors.
   */
  source_sync_run_id uuid,

  source text not null
    default 'listings_sync'
    check (
      char_length(
        btrim(source)
      )
      between 1 and 60
    ),


  -- ----------------------------------------------------------
  -- RELATIONSHIPS
  -- ----------------------------------------------------------

  constraint ml_offer_snapshots_listing_fk
    foreign key (
      organization_id,
      ml_account_id,
      ml_listing_id
    )
    references public.ml_listings (
      organization_id,
      ml_account_id,
      id
    )
    on delete cascade,


  constraint ml_offer_snapshots_variation_fk
    foreign key (
      ml_listing_variation_id
    )
    references public.ml_listing_variations (
      id
    )
    on delete cascade,


  constraint ml_offer_snapshots_product_fk
    foreign key (
      organization_id,
      product_id
    )
    references public.products (
      organization_id,
      id
    )
    on delete set null,


  constraint ml_offer_snapshots_sync_run_fk
    foreign key (
      source_sync_run_id
    )
    references public.sync_runs (
      id
    )
    on delete set null,


  -- ----------------------------------------------------------
  -- SCOPE CONSISTENCY
  -- ----------------------------------------------------------

  constraint ml_offer_snapshots_scope_check
    check (

      (
        offer_scope = 'listing'

        and
        ml_listing_variation_id
          is null

        and
        variation_id
          is null
      )

      or

      (
        offer_scope = 'variation'

        and
        ml_listing_variation_id
          is not null

        and
        variation_id
          is not null
      )

    )
);


comment on table
public.ml_offer_state_snapshots
is
'Historical state changes of Mercado Livre listings and variations used for operational diagnosis.';


-- ============================================================
-- 2. INDEXES
-- ============================================================

create index
ml_offer_snapshots_listing_time_idx
on public.ml_offer_state_snapshots (
  ml_listing_id,
  captured_at desc
);


create index
ml_offer_snapshots_variation_time_idx
on public.ml_offer_state_snapshots (
  ml_listing_variation_id,
  captured_at desc
)
where
  ml_listing_variation_id
    is not null;


create index
ml_offer_snapshots_product_time_idx
on public.ml_offer_state_snapshots (
  product_id,
  captured_at desc
)
where
  product_id
    is not null;


create index
ml_offer_snapshots_account_time_idx
on public.ml_offer_state_snapshots (
  ml_account_id,
  captured_at desc
);


